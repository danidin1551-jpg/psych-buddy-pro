/** ברירת מחדל לסוגי שאלה שאינם במיפוי */
export const DEFAULT_TIME_TARGET_SECONDS = 45;

export function timeTargetSeconds(typeLabel: string): number {
  return TIME_TARGET_SECONDS[typeLabel] ?? DEFAULT_TIME_TARGET_SECONDS;
}

/** אותו יעד במילישניות — נוחות לחישובים מול Date.now() */
export function timeTargetMs(typeLabel: string): number {
  return timeTargetSeconds(typeLabel) * 1000;
}
